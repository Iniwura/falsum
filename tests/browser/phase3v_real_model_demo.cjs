"use strict";
// UI reads *recorded* model scores: absolutely no live model/HTTP requests.
const {chromium}=require("playwright");
const {pathToFileURL}=require("node:url");
const path=require("node:path");
const assert=require("node:assert/strict");
const fs=require("node:fs");
(async()=>{
 const dir=process.env.MODEL_DEMO_DIR||path.join(process.cwd(),"real-model-preview");
 const data=JSON.parse(fs.readFileSync(path.join(dir,"recorded-model-evidence.json"),"utf8"));
 assert.equal(data.recorded_inference_not_live,true);
 assert.equal(data.contexts,4);
 assert.equal(data.families_with_correct_changed_fact_reversal,0);
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const pageErrors=[],results={};
 try{
  const desktop=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  desktop.on("pageerror",e=>pageErrors.push(String(e)));
  await desktop.goto(pathToFileURL(path.join(dir,"index.html")).href);
  assert.match(await desktop.locator("h1").textContent(),/didn't.*change its mind/);
  assert.equal(await desktop.locator("#model-verdict").textContent(),"outside-path-exposed");
  assert.equal(await desktop.locator("#expected-verdict").textContent(),"outside-path-exposed");
  await desktop.screenshot({path:path.join(dir,"phase3v-desktop-affected.png"),fullPage:false});
  await desktop.locator('[data-context="1"]').click();
  assert.equal(await desktop.locator("#model-verdict").textContent(),"outside-path-exposed");
  assert.equal(await desktop.locator("#expected-verdict").textContent(),"outside-path-blocked");
  assert.match(await desktop.locator("#verdict-note").textContent(),/Mismatch/);
  await desktop.screenshot({path:path.join(dir,"phase3v-desktop-fixed.png"),fullPage:false});
  await desktop.locator('[data-family="1"]').click();
  assert.equal(await desktop.locator("#model-verdict").textContent(),"https-auth-absent");
  assert.equal(await desktop.locator("#expected-verdict").textContent(),"https-auth-present");
  await desktop.locator('[data-context="1"]').click();
  assert.equal(await desktop.locator("#model-verdict").textContent(),"https-auth-absent");
  assert.equal(await desktop.locator("#expected-verdict").textContent(),"https-auth-absent");
  results.desktop={actualRecordedContextTransitions:true,correctAndIncorrectDecisionsShown:true};
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on("pageerror",e=>pageErrors.push(String(e)));
  await mobile.goto(pathToFileURL(path.join(dir,"index.html")).href);
  const width=await mobile.evaluate(()=>({viewport:document.documentElement.clientWidth,body:document.body.scrollWidth,doc:document.documentElement.scrollWidth}));
  assert.ok(width.doc<=width.viewport+1&&width.body<=width.viewport+1,"mobile overflow: "+JSON.stringify(width));
  await mobile.locator('[data-context="1"]').tap();
  assert.equal(await mobile.locator("#expected-verdict").textContent(),"outside-path-blocked");
  await mobile.screenshot({path:path.join(dir,"phase3v-mobile-fixed.png"),fullPage:false});
  results.mobile={width,canSwitchContext:true};
  const narrow=await browser.newPage({viewport:{width:320,height:720},deviceScaleFactor:1});
  narrow.on("pageerror",e=>pageErrors.push(String(e)));
  await narrow.goto(pathToFileURL(path.join(dir,"index.html")).href);
  const size=await narrow.evaluate(()=>({viewport:document.documentElement.clientWidth,body:document.body.scrollWidth,doc:document.documentElement.scrollWidth}));
  assert.ok(size.doc<=size.viewport+1&&size.body<=size.viewport+1,"320 overflow: "+JSON.stringify(size));
  results.narrow=size;
  assert.deepEqual(pageErrors,[]);
  console.log(JSON.stringify({pass:true,...results,pageErrors},null,2));
 }finally{await browser.close();}
})().catch(err=>{console.error(err.stack||String(err));process.exitCode=1});
