import base64
import copy
import json
import unittest

from falsum import phase5au_solana_anchor_evidence as anchor
from falsum import phase5bb_acp_security_acceptance as gate
from falsum import phase5bd_acp_provider_prepare as provider
from falsum import phase5bg_telegraph_acp_binding as binding
from falsum.phase5aj_cross_app_evidence import source_bytes


def raw_json(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


def b64(raw):
    return base64.b64encode(raw).decode("ascii")


class TelegraphAcpBindingTests(unittest.TestCase):
    """All fixtures here are constructed; none is a paid capture or live ACP job."""

    @classmethod
    def setUpClass(cls):
        cls.advisory = source_bytes(next(
            source for source in anchor.protocol()["sources"]
            if source["key"] == "reviewed_advisory"
        ))

    def manifest(self):
        buyer = "0x" + "2" * 40
        payer = buyer
        original = {
            "schema": gate.SCHEMA,
            "chain_id": binding.TELEGRAPH_CHAIN_ID,
            "job_id": "9001",  # Explicit fixture input; never generated by the verifier.
            "intent": binding.TELEGRAPH_INTENT,
            "target": {
                "ecosystem": "crates.io",
                "package": "anchor-lang",
                "version": "1.0.1",
                "reference": "GHSA-c6rc-8jpp-2fgc",
            },
        }
        response = {
            "intent": binding.TELEGRAPH_INTENT,
            "job_id": original["job_id"],
            "report_job": copy.deepcopy(original),
            "answer": "CONSTRUCTED TEST RESPONSE ONLY",
        }
        request_raw = binding.ANCHOR_REQUEST_BYTES
        response_raw = raw_json(response)
        tx_hash = "0x" + "a" * 64
        receipt_hash = "0x" + "b" * 64
        receipt = {
            "intent": binding.TELEGRAPH_INTENT,
            "amount": binding.TELEGRAPH_AMOUNT,
            "network": binding.TELEGRAPH_NETWORK,
            "asset": binding.TELEGRAPH_ASSET,
            "payTo": binding.TELEGRAPH_PAY_TO,
            "tx_hash": tx_hash,
            "receipt_hash": receipt_hash,
            "job_id": original["job_id"],
            "request_sha256": binding.bytes_digest(request_raw),
            "response_sha256": binding.bytes_digest(response_raw),
        }
        report_response = {
            "claim": "APPLICABLE",
            "verdict": "Insecure",
            "vulnerability_count": 1,
            "issues": ["Constructed scoped applicability claim"],
            "summary": "Constructed scoped applicability claim.",
        }
        report = {
            "schema": gate.SCHEMA,
            "chain_id": original["chain_id"],
            "job_id": original["job_id"],
            "target": copy.deepcopy(original["target"]),
            "claim": "APPLICABLE",
            "response": report_response,
            "receipt_hash": receipt_hash,
        }
        outer_job_id = "77"
        requirement_binding = {
            "schema": binding.BINDING_REF_SCHEMA,
            "request_sha256": binding.bytes_digest(request_raw),
            "response_sha256": binding.bytes_digest(response_raw),
            "receipt_hash": receipt_hash,
            "tx_hash": tx_hash,
            "report_job_digest": binding.digest(original),
        }
        requirement = {
            "schema": binding.REQUEST_SCHEMA_V2,
            "offering": provider.OFFERING,
            "report_job": copy.deepcopy(original),
            "report": report,
            "telegraph_binding": requirement_binding,
        }
        requirement_raw = raw_json(requirement)
        entries = [
            {"kind": "system", "event": {"type": "job.created"}},
            {"kind": "message", "from": buyer, "contentType": "requirement",
             "content": requirement_raw.decode("utf-8")},
            {"kind": "system", "event": {"type": "budget.set"}},
            {"kind": "system", "event": {"type": "job.funded"}},
        ]
        history = {
            "protocol": "v2", "status": "funded", "chainId": binding.ACP_CHAIN_ID,
            "jobId": outer_job_id, "entryCount": len(entries), "entries": entries,
        }
        delivery = {
            "schema": provider.RESULT_SCHEMA,
            "offering": provider.OFFERING,
            "verification_job": {"chain_id": binding.ACP_CHAIN_ID, "job_id": outer_job_id},
            "requirement_digest": binding.digest(requirement),
            "history_digest": binding.digest(history),
            "report_evaluation": gate.evaluate(
                original,
                report,
                {
                    "status": "CALLER_VERIFIED",
                    "job_digest": binding.digest(original),
                    "response_digest": binding.digest(report["response"]),
                    "receipt_hash": receipt_hash,
                    "intent": binding.TELEGRAPH_INTENT,
                },
                self.advisory,
            ),
            "telegraph_binding": requirement_binding,
        }
        return {
            "schema": binding.SCHEMA,
            "classification": "CONSTRUCTED_TEST",
            "telegraph": {
                "request_url": binding.TELEGRAPH_URL,
                "request_body_b64": b64(request_raw),
                "request_sha256": binding.bytes_digest(request_raw),
                "quote": {
                    "scheme": binding.TELEGRAPH_SCHEME,
                    "network": binding.TELEGRAPH_NETWORK,
                    "asset": binding.TELEGRAPH_ASSET,
                    "payTo": binding.TELEGRAPH_PAY_TO,
                    "amount": binding.TELEGRAPH_AMOUNT,
                    "maxTimeoutSeconds": 60,
                },
                "payment_response_header": "constructed-payment-response",
                "receipt_header": json.dumps(receipt, sort_keys=True, separators=(",", ":")),
                "receipt": receipt,
                "response_body_b64": b64(response_raw),
                "response_sha256": binding.bytes_digest(response_raw),
                "payment_transfer": {
                    "chain_id": binding.TELEGRAPH_CHAIN_ID,
                    "tx_hash": tx_hash,
                    "status": "0x1",
                    "token": binding.TELEGRAPH_ASSET,
                    "from": payer,
                    "to": binding.TELEGRAPH_PAY_TO,
                    "amount": binding.TELEGRAPH_AMOUNT,
                },
            },
            "acp": {
                "chain_id": binding.ACP_CHAIN_ID,
                "job_id": outer_job_id,
                "buyer": buyer,
                "provider": binding.FALSUM_PROVIDER_WALLET,
                "requirement_body_b64": b64(requirement_raw),
                "requirement_sha256": binding.bytes_digest(requirement_raw),
                "history_body_b64": b64(raw_json(history)),
                "history_sha256": binding.bytes_digest(raw_json(history)),
            },
            "delivery": {
                "body_b64": b64(raw_json(delivery)),
                "sha256": binding.bytes_digest(raw_json(delivery)),
            },
        }

    def reencode_response(self, manifest, response):
        raw = raw_json(response)
        telegraph = manifest["telegraph"]
        telegraph["response_body_b64"] = b64(raw)
        telegraph["response_sha256"] = binding.bytes_digest(raw)
        receipt = copy.deepcopy(telegraph["receipt"])
        receipt["response_sha256"] = telegraph["response_sha256"]
        telegraph["receipt"] = receipt
        telegraph["receipt_header"] = json.dumps(receipt, sort_keys=True, separators=(",", ":"))

    def reencode_requirement(self, manifest, requirement):
        raw = raw_json(requirement)
        history = json.loads(base64.b64decode(manifest["acp"]["history_body_b64"]).decode("utf-8"))
        for entry in history["entries"]:
            if entry.get("kind") == "message" and entry.get("contentType") == "requirement":
                entry["content"] = raw.decode("utf-8")
        history_raw = raw_json(history)
        acp = manifest["acp"]
        acp["requirement_body_b64"] = b64(raw)
        acp["requirement_sha256"] = binding.bytes_digest(raw)
        acp["history_body_b64"] = b64(history_raw)
        acp["history_sha256"] = binding.bytes_digest(history_raw)

    def test_constructed_exact_binding(self):
        out = binding.verify(self.manifest())
        self.assertEqual(out["decision"], "BOUND")
        self.assertTrue(out["binding_verified"])
        self.assertFalse(out["independent_customer_adoption"])
        self.assertFalse(out["purchase_authorized"])

    def test_missing_original_job_id_is_hold(self):
        manifest = self.manifest()
        response = json.loads(base64.b64decode(manifest["telegraph"]["response_body_b64"]).decode("utf-8"))
        del response["report_job"]["job_id"]
        self.reencode_response(manifest, response)
        self.assertEqual(binding.verify(manifest)["reasons"], ["INVALID_ORIGINAL_REPORT_JOB"])

    def test_receipt_must_bind_request_and_response(self):
        manifest = self.manifest()
        receipt = manifest["telegraph"]["receipt"]
        del receipt["request_sha256"]
        manifest["telegraph"]["receipt_header"] = json.dumps(receipt, sort_keys=True, separators=(",", ":"))
        self.assertEqual(binding.verify(manifest)["reasons"], ["RECEIPT_MISSING_BINDING_FIELDS"])

    def test_request_digest_or_target_tamper_holds(self):
        manifest = self.manifest()
        raw = json.dumps({"intent": binding.TELEGRAPH_INTENT, "params": {"target": "tampered"}},
                         sort_keys=True, separators=(",", ":")).encode("ascii")
        manifest["telegraph"]["request_body_b64"] = b64(raw)
        manifest["telegraph"]["request_sha256"] = binding.bytes_digest(raw)
        self.assertEqual(binding.verify(manifest)["reasons"], ["TELEGRAPH_REQUEST_TARGET_MISMATCH"])

    def test_transfer_must_match_receipt(self):
        manifest = self.manifest()
        manifest["telegraph"]["payment_transfer"]["token"] = "0x" + "c" * 40
        self.assertEqual(binding.verify(manifest)["reasons"], ["INDEPENDENT_TRANSFER_DOES_NOT_MATCH_RECEIPT"])

    def test_current_v1_report_job_schema_is_explicit_blocker(self):
        manifest = self.manifest()
        requirement = json.loads(base64.b64decode(manifest["acp"]["requirement_body_b64"]).decode("utf-8"))
        requirement["schema"] = provider.REQUEST_SCHEMA
        del requirement["telegraph_binding"]
        self.reencode_requirement(manifest, requirement)
        self.assertEqual(binding.verify(manifest)["reasons"], ["REPORT_JOB_SCHEMA_LIMITATION"])

    def test_acp_history_and_delivery_binding_are_exact(self):
        manifest = self.manifest()
        history = json.loads(base64.b64decode(manifest["acp"]["history_body_b64"]).decode("utf-8"))
        history["jobId"] = "78"
        raw = raw_json(history)
        manifest["acp"]["history_body_b64"] = b64(raw)
        manifest["acp"]["history_sha256"] = binding.bytes_digest(raw)
        self.assertEqual(binding.verify(manifest)["reasons"], ["ACP_HISTORY_JOB_ID_MISMATCH"])

        manifest = self.manifest()
        delivery = json.loads(base64.b64decode(manifest["delivery"]["body_b64"]).decode("utf-8"))
        delivery["telegraph_binding"]["response_sha256"] = "0" * 64
        raw = raw_json(delivery)
        manifest["delivery"]["body_b64"] = b64(raw)
        manifest["delivery"]["sha256"] = binding.bytes_digest(raw)
        self.assertEqual(binding.verify(manifest)["reasons"], ["FALSUM_DELIVERY_BINDING_MISMATCH"])


if __name__ == "__main__":
    unittest.main()
