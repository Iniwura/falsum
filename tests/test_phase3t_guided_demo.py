"""Phase 3T: judge-understandable guided security review demo release gates.

This site is a PUBLIC educational interaction driven by real Python case outputs.
Two sample reviews per case are handcrafted, not live-model predictions or the
network's confidential evaluation pairs.
"""
from __future__ import annotations

from pathlib import Path
import hashlib
import json
import tempfile
import unittest

from falsum.phase3q_mission_lab import capture, write_outputs

ROOT=Path(__file__).resolve().parents[1]
TEMPLATE=ROOT/"src/falsum/templates/firma_editorial_evidence_lab.html"


class GuidedSecurityReviewDemo(unittest.TestCase):
    def test_one_clearly_explained_journey_from_question_to_real_proof(self):
        t=TEMPLATE.read_text()
        expected=(
            "PICK THE",
            "BETTER",
            'id="scene-explain"',
            'id="answer-a"',
            'id="show-proof"',
            'class="answers"',
            'id="answer-a"',
            'id="answer-b"',
            'id="show-proof"',
            'id="next-case"',
            'id="try-again"',
            'id="final-score"',
            'id="feedback"',
            'id="proof"',
            'id="code-before"',
            'id="code-after"',
            'id="hash-before"',
            'id="hash-after"',
            "Choose A or B first.",
            "not generated by a live model",
        )
        for text in expected:
            with self.subTest(expected=text):
                self.assertIn(text,t)

    def test_all_three_handwritten_review_examples_exist_but_not_network_rows(self):
        t=TEMPLATE.read_text()
        self.assertIn('id:"exchange-owner-binding"',t)
        self.assertIn('id:"model-agent-callback-integrity"',t)
        self.assertIn('id:"web3-relayer-replay"',t)
        self.assertIn("correct:1",t)
        self.assertIn("correct:0",t)
        self.assertIn("The examples above are written for this demo",t)
        self.assertIn("not generated by a live model",t)
        self.assertIn("The examples above are written for this demo",t)
        self.assertIn("20 evaluation pairs appear eligible",t)
        for sensitive in ("PRIVATE-EVALPOOL-ROWS","0x9cBA6Cf","issuecomment-6588168396","X-Evalpool-Signature"):
            self.assertNotIn(sensitive,t)

    def test_authentic_captured_execution_drives_results_not_placeholder_counts(self):
        report=capture()
        self.assertEqual(report["synthetic_unwanted_actions_observed_before"],3)
        self.assertEqual(report["synthetic_unwanted_actions_blocked_after"],3)
        self.assertEqual(report["legitimate_controls_preserved_after"],3)
        for case in report["cases"]:
            self.assertEqual(hashlib.sha256(case["before_code"].encode()).hexdigest(),case["before_source_sha256"])
            self.assertEqual(hashlib.sha256(case["after_code"].encode()).hexdigest(),case["after_source_sha256"])
            self.assertTrue(case["before"]["unsafe_action_accepted"])
            self.assertFalse(case["after"]["unsafe_action_accepted"])
            self.assertTrue(case["after"]["control_action_accepted"])
        with tempfile.TemporaryDirectory() as temp:
            folder=Path(temp)/"site"
            write_outputs(folder,report)
            page=(folder/"index.html").read_text()
            data=json.loads((folder/"ACTUAL-SYNTHETIC-RUNTIME-PROOF.json").read_text())
            self.assertEqual(data,report)
            self.assertNotIn("__FALSUM_DATA__",page)
            self.assertIn('id="proof-data"',page)
            self.assertIn("function render()",page)
            self.assertEqual(page.count('type="application/json"'),1)
            self.assertIn('if (!Array.isArray(cases)',page)
            self.assertNotIn("0x9cBA6Cf",page)

    def test_feedback_and_completion_have_real_state_transitions(self):
        t=TEMPLATE.read_text()
        self.assertIn("picks[current]=i",t)
        self.assertIn("render();",t)
        self.assertIn("score=picks.reduce",t)
        self.assertIn("picks.fill(null)",t)
        self.assertIn('if(!revealed)return',t)
        self.assertIn('if(picks[current]===null)return',t)
        self.assertIn('selected===e.correct',t)
        self.assertIn('document.querySelector(".code-details").open=false',t)
        self.assertIn('button.disabled=selected!==null',t)
        self.assertIn('aria-live="polite" role="status"',t)

    def test_accessibility_mobile_motion_and_private_data_guard(self):
        t=TEMPLATE.read_text()
        self.assertIn("@media(max-width:1000px)",t)
        self.assertIn("@media(max-width:650px)",t)
        self.assertIn("prefers-reduced-motion:reduce",t)
        self.assertIn("aria-pressed",t)
        self.assertIn('aria-label="Choose the better review"',t)
        self.assertIn("scrollIntoView",t)
        self.assertIn("aria-live",t)
        self.assertNotIn("fetch(",t)
        self.assertNotIn("WebSocket",t)
        self.assertNotIn("localStorage",t)
        self.assertNotIn("https://fonts.",t)
        self.assertNotIn("<img",t)


if __name__=="__main__":
    unittest.main()
